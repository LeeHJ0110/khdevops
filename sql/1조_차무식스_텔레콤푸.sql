DECLARE
    V_PENALTY_COUNT NUMBER := 0;
    V_EXTRA_COUNT   NUMBER := TRUNC(DBMS_RANDOM.VALUE(1, 3)); -- 1~2건
    V_FEE           NUMBER;
BEGIN
    INSERT INTO BILLING (
        NO,
        FIXED_NO,
        PLAN_CONTRACT_NO,
        BILL_MONTH,
        BILL_TOTAL,
        ETC_BIL,
        PAY_YN
    )
    SELECT 
        SEQ_BILLING.NEXTVAL,
        FIXED_NO,
        NO,
        USED_MONTH,
        0,
        0,
        CASE WHEN DBMS_RANDOM.VALUE < 0.5 THEN 'Y' ELSE 'N' END
    FROM (
        SELECT 
            PC.*,
            ROW_NUMBER() OVER (PARTITION BY FIXED_NO, USED_MONTH ORDER BY NO) RN
        FROM PLAN_CONTRACT PC
    )
    WHERE RN = 1;

    -- 기존: 위약금 3건
    FOR rec IN (
        SELECT NO FROM (
            SELECT NO FROM BILLING ORDER BY DBMS_RANDOM.VALUE
        ) WHERE ROWNUM <= 3
    ) LOOP
        V_FEE := TRUNC(DBMS_RANDOM.VALUE(10000, 50000), -2);

        UPDATE BILLING 
        SET ETC_BIL = V_FEE,
            BILL_TOTAL = BILL_TOTAL + V_FEE
        WHERE NO = rec.NO;
    END LOOP;

    -- 추가: 1~2건 약 10000원
    FOR rec IN (
        SELECT NO FROM (
            SELECT NO FROM BILLING 
            WHERE ETC_BIL = 0   -- 이미 선택된 것 제외
            ORDER BY DBMS_RANDOM.VALUE
        ) WHERE ROWNUM <= V_EXTRA_COUNT
    ) LOOP
        V_FEE := TRUNC(DBMS_RANDOM.VALUE(9000, 11000), -2); -- 약 10000

        UPDATE BILLING 
        SET ETC_BIL = V_FEE,
            BILL_TOTAL = BILL_TOTAL + V_FEE
        WHERE NO = rec.NO;
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('BILLING 생성 완료 (위약금 3건 + 소액 ' || V_EXTRA_COUNT || '건)');
