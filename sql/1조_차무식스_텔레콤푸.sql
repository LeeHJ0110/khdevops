        CONFIRM_STATUS
    )
    WITH RAW_DATA AS (
        SELECT 
            NO AS SC_NO,
            FIXED_NO AS F_NO,
            DEL_DATE AS SC_DEL_DATE,
            ROW_NUMBER() OVER (ORDER BY DBMS_RANDOM.VALUE) as RN
        FROM SERVICE_CONTRACT
        WHERE DEL_DATE IS NOT NULL 
    )
    SELECT 
        SEQ_SERVICE_DELETE_CONFIRM.NEXTVAL,
        CASE 
            WHEN STATUS_SEED < 0.2 THEN NULL 
            ELSE TRUNC(DBMS_RANDOM.VALUE(1, 3)) 
        END,
        SC_NO, 
        F_NO,
        CASE 
            WHEN STATUS_SEED < 0.2 THEN NULL 
            ELSE SC_DEL_DATE + DBMS_RANDOM.VALUE(0, 3) 
        END,
        CASE 
            WHEN STATUS_SEED < 0.2 THEN 'A'
            WHEN STATUS_SEED < 0.8 THEN 'Y'
            ELSE 'N'
        END
    FROM (
        SELECT SC_NO, F_NO, SC_DEL_DATE, DBMS_RANDOM.VALUE as STATUS_SEED
        FROM RAW_DATA
        WHERE RN <= V_MAX_ROWS 
    );
    COMMIT;
    DBMS_OUTPUT.PUT_LINE(SQL%ROWCOUNT || ' rows inserted into SERVICE_DELETE_CONFIRM.');
END;
