        NO, 
        EMPLOYEE_NO, 
        SERVICE_NO, 
        FIXED_NO, 
        CONFIRM_AT, 
        CONFIRM_STATUS
    )
    WITH RAW_DATA AS (
        SELECT 
            F_NO, 
            S_NO,
            ROW_NUMBER() OVER (ORDER BY DBMS_RANDOM.VALUE) as RN
        FROM (SELECT LEVEL F_NO FROM DUAL CONNECT BY LEVEL <= 20)
        CROSS JOIN (SELECT LEVEL S_NO FROM DUAL CONNECT BY LEVEL <= 30)
    )
    SELECT 
        SEQ_SERVICE_INSERT_CONFIRM.NEXTVAL,
        CASE 
            WHEN STATUS_SEED < 0.3 THEN NULL
            ELSE TRUNC(DBMS_RANDOM.VALUE(1, 3))
        END as EMPLOYEE_NO,
        S_NO as SERVICE_NO,
        F_NO as FIXED_NO,
        CASE 
            WHEN STATUS_SEED < 0.3 THEN NULL
            ELSE SYSDATE - DBMS_RANDOM.VALUE(0, 30)
        END as CONFIRM_AT,
        CASE 
            WHEN STATUS_SEED < 0.3 THEN 'A'
            WHEN STATUS_SEED < 0.7 THEN 'Y'
            ELSE 'N'
        END as CONFIRM_STATUS
    FROM (
        SELECT F_NO, S_NO, DBMS_RANDOM.VALUE as STATUS_SEED
        FROM RAW_DATA
        WHERE RN <= V_MAX_ROWS
    );
    COMMIT;
    DBMS_OUTPUT.PUT_LINE(V_MAX_ROWS || ' rows inserted into SERVICE_INSERT_CONFIRM.');
