DECLARE
    V_MAX_SERVICES_PER_BILL NUMBER := 5; 
BEGIN
    DELETE FROM SERVICE_CONTRACT;

    FOR rec IN (SELECT NO, FIXED_NO, BILL_MONTH FROM BILLING) LOOP
        
        INSERT INTO SERVICE_CONTRACT (
            NO,
            FIXED_NO,
            SERVICE_NO,
            BILL_NO,
            USED_MONTH,
            DISCOUNT_RATE,
            DEL_DATE
        )
        SELECT 
            SEQ_SERVICE_CONTRACT.NEXTVAL,
            rec.FIXED_NO,
            S_NO,
            rec.NO,
            rec.BILL_MONTH,
            CASE WHEN DBMS_RANDOM.VALUE < 0.9 THEN 0 ELSE 100 END,
            CASE 
                WHEN DBMS_RANDOM.VALUE < 0.2 
                THEN TO_DATE(rec.BILL_MONTH || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(1, 29)), 'FM00'), 'YYYYMMDD')
                ELSE NULL 
            END
        FROM (
            SELECT S_NO 
            FROM (
                SELECT LEVEL AS S_NO FROM DUAL CONNECT BY LEVEL <= 30
                MINUS
                SELECT SERVICE_NO FROM SERVICE_CONTRACT WHERE FIXED_NO = rec.FIXED_NO AND BILL_NO = rec.NO
            )
            ORDER BY DBMS_RANDOM.VALUE
        )
        WHERE ROWNUM <= TRUNC(DBMS_RANDOM.VALUE(1, V_MAX_SERVICES_PER_BILL + 1));
        
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('SERVICE_CONTRACT 대량 생성이 완료되었습니다. (건당 최대 5개 서비스)');
